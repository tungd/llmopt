  | Gemm_8x32x64 | Gemm_8x32x128 -> (32, 8, 1)
  | Gemm_32x32x64 | Gemm_32x32x128 -> (32, 32, 1)
  | Gemm_16x16x128 -> (16, 16, 1)
  | Gemv_single | Gemv_pair -> (256, 1, 1)

